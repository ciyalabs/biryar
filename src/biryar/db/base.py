"""The declarative base, the column vocabulary, and the tenant mixin.

## Why money is never a float

The database this replaces stored revenue and fees as SQLite ``REAL``. Binary
floating point cannot represent 0.10, so a column of them does not add up to
what a human adding the same invoice gets, and the error is not stable: it
depends on the order of summation. Every monetary column here is
``NUMERIC``, and every monetary value in Python is a :class:`~decimal.Decimal`
from the moment it is parsed to the moment it is rendered.

## Why every timestamp carries a zone

``TIMESTAMP WITHOUT TIME ZONE`` is a wall clock with no claim about where the
wall is. A seller in Ludwigsburg, a marketplace in Ireland and a server in
Virginia disagree about what "2026-10-12 00:00" means, and a settlement
posted an hour either side of midnight lands in the wrong day's totals. Every
timestamp is ``TIMESTAMPTZ`` and every value is timezone-aware UTC.

## Why constraints are named by a convention

Alembic can only emit ``DROP CONSTRAINT`` for a constraint whose name it can
predict. Without a naming convention, PostgreSQL invents names, autogenerated
downgrades silently omit them, and a migration becomes one-way. The
convention below makes every constraint name a pure function of the table and
columns it covers.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from decimal import Decimal
from typing import Annotated

from sqlalchemy import BigInteger, DateTime, ForeignKey, MetaData, Numeric, String, func
from sqlalchemy.dialects.postgresql import UUID as PgUUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, registry

NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

metadata = MetaData(naming_convention=NAMING_CONVENTION)

# -- the column vocabulary ----------------------------------------------------------

#: A monetary amount. Four decimal places, not two: Amazon states per-unit fees
#: and FX rates at a finer grain than a price, and rounding on the way in loses
#: money that rounding on the way out cannot recover.
Money = Annotated[Decimal, mapped_column(Numeric(16, 4))]

#: A rate or share in [0, 1], at a precision that survives being multiplied by
#: a price without the product needing to be re-rounded.
Rate = Annotated[Decimal, mapped_column(Numeric(9, 6))]

#: A quantity of sellable units.
Units = Annotated[int, mapped_column(BigInteger)]

Uuid = Annotated[uuid.UUID, mapped_column(PgUUID(as_uuid=True))]
Timestamp = Annotated[datetime, mapped_column(DateTime(timezone=True))]

Sku = Annotated[str, mapped_column(String(64))]
Asin = Annotated[str, mapped_column(String(16))]
ShortText = Annotated[str, mapped_column(String(128))]
LongText = Annotated[str, mapped_column(String(1024))]


class Base(DeclarativeBase):
    """Declarative base for every table in the platform."""

    metadata = metadata
    registry = registry(
        type_annotation_map={
            Decimal: Numeric(16, 4),
            datetime: DateTime(timezone=True),
            uuid.UUID: PgUUID(as_uuid=True),
        }
    )


class TimestampMixin:
    """When the row was written, and when it was last changed."""

    created_at: Mapped[Timestamp] = mapped_column(
        server_default=func.now(), nullable=False,
    )
    updated_at: Mapped[Timestamp] = mapped_column(
        server_default=func.now(), onupdate=func.now(), nullable=False,
    )


class TenantScoped:
    """Marks a table as belonging to exactly one tenant.

    Inheriting this does three things. It adds the ``tenant_id`` column, it
    adds the foreign key that makes an orphaned row impossible, and it marks
    the table for the row-level-security policy that the migration applies.

    **The mixin is not what isolates tenants.** A policy in the database does
    that, so a query someone forgets to filter returns nothing rather than
    returning another seller's figures. The mixin exists so that the set of
    tables needing a policy is derivable from the models instead of
    maintained by hand in a list that drifts.
    """

    __biryar_tenant_scoped__ = True

    @property
    def _tenant_declared(self) -> bool:                      # pragma: no cover
        return True


def tenant_fk() -> Mapped[uuid.UUID]:
    """The tenant column, as every tenant-scoped table declares it."""
    return mapped_column(
        PgUUID(as_uuid=True),
        ForeignKey("tenants.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )


def tenant_scoped_tables() -> list[str]:
    """Every table whose model inherits :class:`TenantScoped`.

    The migration that enables row-level security reads this, so adding a
    tenant-scoped model cannot leave its policy behind.
    """
    names: list[str] = []
    for mapper in Base.registry.mappers:
        cls = mapper.class_
        if getattr(cls, "__biryar_tenant_scoped__", False):
            names.append(cls.__tablename__)
    return sorted(set(names))
